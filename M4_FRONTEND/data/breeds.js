export function getBreedById(id) {
  return BREEDS.find((breed) => breed.id === id)
}

export function getRelatedBreeds(breed, limit = 4) {
  if (!breed) return []
  const sameType = BREEDS.filter((b) => b.id !== breed.id && b.type === breed.type)
  const rest = BREEDS.filter((b) => b.id !== breed.id && b.type !== breed.type)
  return [...sameType, ...rest].slice(0, limit)
}
